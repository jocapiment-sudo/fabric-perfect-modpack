/**
 * Bundles `src/main.ts` into `apotheosis_bp/scripts/main.js`.
 *
 * Why bundle? Bedrock supports ES modules and relative imports, but shipping a
 * single readable file makes the behaviour pack self-contained and removes any
 * resolution surprises on Realms / consoles.
 *
 * `@minecraft/server` and `@minecraft/server-ui` stay external: Bedrock's
 * script runtime provides them according to the manifest dependencies.
 */

import { build } from 'esbuild';
import { mkdir } from 'node:fs/promises';

const OUT_DIR = 'apotheosis_bp/scripts';
const OUT_FILE = `${OUT_DIR}/main.js`;

await mkdir(OUT_DIR, { recursive: true });

await build({
  entryPoints: ['src/main.ts'],
  outfile: OUT_FILE,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2020',
  external: ['@minecraft/server', '@minecraft/server-ui'],
  minify: false,
  sourcemap: false,
  legalComments: 'none',
  banner: {
    js: [
      '// ==========================================================================',
      '//  Apotheosis: Bedrock Edition — compiled bundle',
      '//  Source: src/  |  Rebuild with: npm run build',
      '//  Do not edit this file directly.',
      '// ==========================================================================',
    ].join('\n'),
  },
});

console.log(`✔ Built ${OUT_FILE}`);
