def _pack_icon(center_factory, accent):
    """Build a 32x32 icon then upscale it 4x so the pixels stay crisp."""
    canvas = Image.new('RGBA', (32, 32), (34, 20, 52, 255))

    # Purple gradient backdrop, brighter at the top so the icon reads on dark UIs.
    for y in range(32):
        mix = y / 31
        r = int(72 - mix * 34)
        g = int(34 - mix * 14)
        b = int(104 - mix * 44)
        row(canvas, y, 0, 31, (r, g, b, 255))

    # Soft glow behind the centre art.
    for y in range(32):
        for x in range(32):
            dx, dy = x - 15.5, y - 15.5
            distance = (dx * dx + dy * dy) ** 0.5
            if distance < 11:
                strength = 1 - distance / 11
                r, g, b, a = canvas.getpixel((x, y))
                canvas.putpixel(
                    (x, y),
                    (
                        min(255, int(r + strength * 46)),
                        min(255, int(g + strength * 34)),
                        min(255, int(b + strength * 70)),
                        a,
                    ),
                )

    # Gold frame with a lighter inner bevel.
    for x in range(32):
        canvas.putpixel((x, 0), GOLD_D)
        canvas.putpixel((x, 31), GOLD_D)
        canvas.putpixel((x, 1), GOLD if 1 < x < 30 else GOLD_D)
        canvas.putpixel((x, 30), GOLD_D)
    for y in range(32):
        canvas.putpixel((0, y), GOLD_D)
        canvas.putpixel((31, y), GOLD_D)
    for x, y in ((1, 1), (30, 1), (1, 30), (30, 30)):
        canvas.putpixel((x, y), GOLD)
    for x in range(5, 27, 7):
        canvas.putpixel((x, 2), accent)
        canvas.putpixel((31 - x, 29), accent)

    # Centre art: the 16x16 texture scaled up into the middle of the icon.
    art = center_factory().resize((20, 20), Image.NEAREST)
    canvas.alpha_composite(art, (6, 6))

    # Corner sparkles.
    for x, y in ((3, 3), (28, 4), (4, 28), (27, 27)):
        canvas.putpixel((x, y), CYAN_L)

    return canvas.resize((128, 128), Image.NEAREST)


def pack_icons():
    """Write pack_icon.png into both packs (shown in the pack picker)."""
    bp_icon = _pack_icon(reforging_hammer, AM_XL)
    rp_icon = _pack_icon(affix_gem, CYAN)

    (ROOT / 'apotheosis_bp' / 'pack_icon.png').write_bytes(_png_bytes(bp_icon))
    (ROOT / 'apotheosis_rp' / 'pack_icon.png').write_bytes(_png_bytes(rp_icon))
    print('  · pack_icon.png (behaviour pack)')
    print('  · pack_icon.png (resource pack)')


def _png_bytes(img):
    from io import BytesIO
    buffer = BytesIO()
    img.save(buffer, format='PNG')
    return buffer.getvalue()


def main():
    print('Generating item textures:')
    for name, factory in ITEM_TEXTURES.items():
        save(factory(), ITEMS, name)

    print('Generating block textures:')
    for name, factory in BLOCK_TEXTURES.items():
        save(factory(), BLOCKS, name)

    print('Generating pack icons:')
    pack_icons()

    print(f'\n✔ {len(ITEM_TEXTURES)} item + {len(BLOCK_TEXTURES)} block textures and 2 pack icons written.')


if __name__ == '__main__':
    main()
