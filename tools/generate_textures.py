#!/usr/bin/env python3
"""
============================================================================
 Apotheosis texture generator
============================================================================
 Every texture in the resource pack is generated by this script, so the art
 is reproducible and reviewable in a diff — a 16x16 PNG is unreadable in a
 code review, but the coordinates below are not.

 Requirements:  Pillow  (pip install pillow)
 Usage:         npm run textures          # or: python3 tools/generate_textures.py

 Output:
   apotheosis_rp/textures/items/apoth_*.png     12 item icons
   apotheosis_rp/textures/blocks/apoth_*.png     3 block faces

 The art direction is deliberately vanilla-adjacent: 16x16, a 4-6 colour
 palette per icon, hard-edged pixels, no anti-aliasing and no partial alpha
 beyond the transparent background.
============================================================================
"""

