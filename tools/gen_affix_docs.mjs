#!/usr/bin/env node
/**
 * ============================================================================
 *  Affix reference generator
 * ============================================================================
 *  The affix list lives in `src/core/affixes.ts` and the rarity ladder in
 *  `src/core/rarity.ts`. Duplicating that data into Markdown by hand guarantees
 *  the docs drift, so this script bundles those two modules with esbuild, runs
 *  the bundle in Node and renders `docs/AFFIXES.md` from the real objects.
 *
 *  Usage: npm run docs:affixes
 * ============================================================================
 */

import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');

/* -------------------------------------------------------------------------- */
/* 1. Bundle the gameplay data                                                */
/* -------------------------------------------------------------------------- */
const tempDir = mkdtempSync(join(tmpdir(), 'apoth-docs-'));
const outfile = join(tempDir, 'affix-data.mjs');

await build({
  stdin: {
    contents: `
      import { AFFIXES } from './src/core/affixes';
      import { RARITIES } from './src/core/rarity';
      process.stdout.write(JSON.stringify({ affixes: AFFIXES, rarities: RARITIES }));
    `,
    resolveDir: ROOT,
    sourcefile: 'affix-docs-entry.ts',
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node18',
  outfile,
  logLevel: 'silent',
});

const raw = execFileSync(process.execPath, [outfile], { encoding: 'utf8' });
rmSync(tempDir, { recursive: true, force: true });

const { affixes, rarities } = JSON.parse(raw);

/* -------------------------------------------------------------------------- */
/* 2. Render                                                                  */
/* -------------------------------------------------------------------------- */

/** Format one potency value using the same units the in-game lore uses. */
function formatValue(unit, value) {
  switch (unit) {
    case 'percent':
      return `+${Math.round(value * 1000) / 10}%`;
    case 'seconds':
      return `+${value}s`;
    case 'ticks':
      return `+${value / 20}s`;
    case 'amplifier':
      return `+${value}`;
    default:
      return `+${value}`;
  }
}

function affixTable(group) {
  const lines = [
    '| Affix | Type | Stat | Common | Uncommon | Rare | Epic | Mythic |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const affix of group) {
    const values = affix.values.map((value) => formatValue(affix.unit, value));
    lines.push(`| **${affix.name}** \`${affix.id}\` | ${affix.kind} | ${affix.label} | ${values.join(' | ')} |`);
  }
  return lines;
}

const lines = [];
lines.push('# Affix reference');
lines.push('');
lines.push('> Generated by `npm run docs:affixes` from `src/core/affixes.ts` and `src/core/rarity.ts`.');
lines.push('> Do not edit this file by hand — edit the TypeScript and regenerate.');
lines.push('');
lines.push('Every number below is the *base* roll. Item level adds up to +50 % on top');
lines.push('(see `levelMultiplier` in `src/core/affixes.ts`), which is why a freshly');
lines.push('reforged Mythic weapon can beat a low-level one of the same rarity.');
lines.push('');

lines.push('## Rarity ladder');
lines.push('');
lines.push('| Rarity | Tier | Affix slots | Reforge cost | Upgrade cost | Loot weight | Salvage |');
lines.push('| --- | --- | --- | --- | --- | --- | --- |');
for (const rarity of rarities) {
  const reforge = `${rarity.reforge.dust} dust + ${rarity.reforge.levels} lvl`;
  const upgrade = rarity.upgrade?.orb ? `${rarity.upgrade.dust} dust + ${rarity.upgrade.levels} lvl + orb` : '—';
  const salvage = `${rarity.salvage.dustMin}–${rarity.salvage.dustMax} dust, ${Math.round(
    rarity.salvage.gemChance * 100,
  )}% gem`;
  lines.push(
    `| ${rarity.name} | ${rarity.tier} | ${rarity.affixSlots} | ${reforge} | ${upgrade} | ${rarity.weight} | ${salvage} |`,
  );
}
lines.push('');
lines.push('Upgrades consume one orb of the *target* rarity band: taking an item from Uncommon to');
lines.push('Rare costs a Rare Orb, Rare to Epic costs an Epic Orb, Epic to Mythic costs a Mythic Orb.');
lines.push('Mythic is the top of the ladder and cannot be upgraded further, only reforged.');
lines.push('');

const weaponAffixes = affixes.filter((affix) => affix.slot === 'weapon');
const armourAffixes = affixes.filter((affix) => affix.slot === 'armor');
const universalAffixes = affixes.filter((affix) => affix.slot === 'any');

lines.push('## Weapon affixes');
lines.push('');
lines.push(...affixTable([...weaponAffixes, ...universalAffixes]));
lines.push('');
lines.push('## Armour affixes');
lines.push('');
lines.push(...affixTable([...armourAffixes, ...universalAffixes]));
lines.push('');
lines.push('Affixes marked "any" can roll on both weapons and armour.');
lines.push('');

lines.push('## How a name is built');
lines.push('');
lines.push('```');
lines.push('Keen Diamond Sword of the Berserker');
lines.push('^^^^ prefix            ^^^^^^^^^^^^^^ suffix');
lines.push('```');
lines.push('');
lines.push('Only the first prefix and the first suffix appear in the title; every affix is');
lines.push('listed in the lore with its rolled value. Items always roll at least one prefix');
lines.push('when they have an affix slot, so names never read oddly (see `rollAffixes`).');
lines.push('');
lines.push('## Affix payload');
lines.push('');
lines.push('Affixes are stored on the item itself in the `apoth:item` dynamic property, so they');
lines.push('survive being traded, stored in a chest, or dropped on the ground:');
lines.push('');
lines.push('```json');
lines.push('{ "v": 1, "r": "rare", "l": 24, "a": [{ "id": "keen", "v": 0.12 }], "b": [], "n": "Keen Iron Sword" }');
lines.push('```');
lines.push('');
lines.push('| Field | Meaning |');
lines.push('| --- | --- |');
lines.push('| `v` | payload version (bumped if the format ever changes) |');
lines.push('| `r` | rarity key: `common`, `uncommon`, `rare`, `epic`, `mythic` |');
lines.push('| `l` | item level, used to scale affix potency |');
lines.push('| `a` | rolled affixes (`id` + rolled value `v`) |');
lines.push('| `b` | socketed gems, each `{ "i": "<affix id>", "r": "<rarity>" }` |');
lines.push('| `n` | cached display name (stripped of formatting codes) |');
lines.push('');

mkdirSync(join(ROOT, 'docs'), { recursive: true });
writeFileSync(join(ROOT, 'docs', 'AFFIXES.md'), `${lines.join('\n')}\n`);
console.log(`✔ Wrote docs/AFFIXES.md (${affixes.length} affixes, ${rarities.length} rarities)`);
